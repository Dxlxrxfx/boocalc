"""Derive lossless display crops and vector isolation masks; never rewrites art.
Optional authoring dependencies: Pillow, numpy, scipy.
The generated JS is committed; Node/browser builds need none of these packages.
"""
from pathlib import Path
import json,hashlib
import numpy as np
from PIL import Image
from scipy.ndimage import label, find_objects, distance_transform_edt

ROOT=Path(__file__).resolve().parents[1]
KEYS=['ac','pm','pct','div','7','8','9','mul','4','5','6','sub','1','2','3','add','bs','0','com','eq']
# Connected component IDs at alpha >= 64, including each character's accessories.
OWNERS={'ac':[2],'pm':[11,7,10,13],'pct':[1],'div':[8,9,12,14],'7':[21],'8':[20],'9':[18],'mul':[22,23,24,25],'4':[34,30,32,38],'5':[31],'6':[36,33,37,39],'sub':[35],'1':[41],'2':[48],'3':[42],'add':[49,40,47],'bs':[61,66,67],'0':[65,55,59,62],'com':[58,56,60,63],'eq':[50,57,64]}
sheets={};frames={};checks=[]

def number(v):
    return str(int(v)) if int(v)==v else ('%.2f'%v).rstrip('0').rstrip('.')

def load(sheet,file):
    image=Image.open(ROOT/'src/assets'/file).convert('RGBA');arr=np.array(image)
    labs,n=label(arr[:,:,3]>=64,np.ones((3,3)))
    boxes=find_objects(labs)
    # Assign faint antialiased edges/background to their nearest solid component.
    _,indices=distance_transform_edt(labs==0,return_indices=True)
    nearest=labs[tuple(indices)]
    sheets[sheet]={'url':'assets/'+file,'width':image.width,'height':image.height}
    return image,arr,labs,boxes,nearest

def add(name,sheet,ids,data):
    image,arr,labs,boxes,nearest=data
    selected=[boxes[i-1] for i in ids]
    x=max(0,min(b[1].start for b in selected)-4)
    y=max(0,min(b[0].start for b in selected)-4)
    right=min(image.width,max(b[1].stop for b in selected)+4)
    bottom=min(image.height,max(b[0].stop for b in selected)+4)
    mask=np.isin(nearest[y:bottom,x:right],ids)
    # Exact scanline rectangles, merged vertically. Native SVG supplies the mask.
    # No resampling, pixel rewriting or optional contour library is required.
    rectangles=[];active={}
    for yy,row in enumerate(mask):
        changes=np.diff(np.r_[False,row,False].astype(int))
        runs=list(zip(np.flatnonzero(changes==1),np.flatnonzero(changes==-1)))
        current={}
        for run_start,run_end in runs:
            pair=(int(run_start),int(run_end))
            if pair in active:
                rect=active.pop(pair);rect[3]+=1
            else:rect=[int(run_start),yy,int(run_end-run_start),1]
            current[pair]=rect
        rectangles.extend(active.values());active=current
    rectangles.extend(active.values())
    paths=[f'M{x0} {y0}h{ww}v{hh}h{-ww}Z' for x0,y0,ww,hh in rectangles]
    path=''.join(paths)
    rect=[int(x),int(y),int(right-x),int(bottom-y)]
    frames[name]={'sheet':sheet,'rect':rect,'clip':path}
    own=np.isin(labs,ids)
    total=int(own.sum());inside=int(own[y:bottom,x:right].sum())
    region=labs[y:bottom,x:right]
    foreign=int(((region>0)&~np.isin(region,ids)&mask).sum())
    assert total==inside,(name,'cropped silhouette')
    assert not foreign,(name,'foreign pixels')
    assert (mask&np.isin(region,ids)).sum()==total
    checks.append({'frame':name,'solid_pixels':total,'solid_pixels_lost':total-inside,'foreign_pixels':foreign,'rect':rect})

assert hashlib.sha256((ROOT/'src/assets/boocalc-sprites.webp').read_bytes()).hexdigest() == '0fac999e7eed358dd29ac5c41aefa62986c9a757827ab234297abc8fffb83140', 'The original atlas changed; review component ownership first.'
original=load('original','boocalc-sprites.webp')
assert original[0].size==(1586,992)
for i,key in enumerate(KEYS):
    x=round((i%4*2+.5)*1586/8);y=round((i//4+.5)*992/5)
    add(key+':button','original',[int(original[2][y,x])],original)
    add(key+':ghost','original',OWNERS[key],original)

supplement=load('supplement','boocalc-supplement.webp')
for third,name in enumerate(['mul:ghost','div:ghost','com-dot:button']):
    image,arr,labs,boxes,nearest=supplement
    x0=round(third*image.width/3);x1=round((third+1)*image.width/3)
    values,counts=np.unique(labs[:,x0:x1],return_counts=True);counts[values==0]=0
    add(name,'supplement',[int(values[counts.argmax()])],supplement)
# The active operator frames replace the two fused legacy character groups.
active={c['frame']:c for c in checks}
header='// Generated by tools/build-sprite-frames.py. Pixel artwork is unchanged.\n'
js=header+'export const SPRITE_ATLASES = '+json.dumps(sheets,ensure_ascii=False,separators=(',',':'))+';\n'
js+='export const SPRITE_FRAMES = '+json.dumps(frames,ensure_ascii=False,separators=(',',':'))+';\n'
(ROOT/'src/sprite-frames.js').write_text(js)
(ROOT/'src/assets/frame-validation.json').write_text(json.dumps({'threshold':64,'active_frames':len(frames),'frames':list(active.values())},indent=2)+'\n')
print(json.dumps({'active_frames':len(frames),'mask_characters':sum(len(f['clip']) for f in frames.values()),'lost':sum(c['solid_pixels_lost'] for c in active.values()),'foreign':sum(c['foreign_pixels'] for c in active.values()),'sheets':sheets}))
